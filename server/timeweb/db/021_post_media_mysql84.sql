-- Explicit reviewed post attachment associations. No profile/message relabel,
-- no guessed object owner and no overwrite of original legacy_storage_objects.
CREATE TABLE clrs_staging.post_media (
  post_id VARCHAR(191) NOT NULL,
  media_id VARCHAR(191) NOT NULL CHECK (media_id REGEXP '^tw-post-media-[a-f0-9]{64}$'),
  source_generation_id BINARY(32) NOT NULL,
  source_root_sha256 BINARY(32) NOT NULL,
  source_bucket VARCHAR(191) NOT NULL,
  source_path LONGTEXT NOT NULL,
  source_path_sha256 BINARY(32) GENERATED ALWAYS AS (UNHEX(SHA2(source_path,256))) STORED,
  source_metadata JSON NOT NULL CHECK (JSON_TYPE(source_metadata)='OBJECT'),
  source_metadata_sha256 BINARY(32) NOT NULL,
  source_byte_size BIGINT NOT NULL CHECK (source_byte_size BETWEEN 1 AND 5242880),
  source_sha256 BINARY(32) NOT NULL,
  source_archive_sha256 BINARY(32) NOT NULL,
  target_key TEXT NOT NULL,
  target_key_sha256 BINARY(32) GENERATED ALWAYS AS (UNHEX(SHA2(target_key,256))) STORED,
  target_byte_size BIGINT NOT NULL,
  target_sha256 BINARY(32) NOT NULL,
  mime_type VARCHAR(191) NOT NULL CHECK (mime_type IN ('image/jpeg','image/png','image/webp')),
  reference_fields JSON NOT NULL CHECK (JSON_TYPE(reference_fields)='ARRAY'),
  verified_bytes_proof_sha256 BINARY(32) NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status='ready'),
  verified_at DATETIME(6) NOT NULL,
  CONSTRAINT post_media_target_size_ck CHECK (target_byte_size=source_byte_size),
  CONSTRAINT post_media_target_sha_ck CHECK (target_sha256=source_sha256),
  PRIMARY KEY (post_id),
  UNIQUE KEY post_media_id_uq (media_id),
  CONSTRAINT post_media_post_fk FOREIGN KEY (post_id) REFERENCES clrs_staging.posts(post_id)
) ENGINE=InnoDB ROW_FORMAT=DYNAMIC DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
